let handler = async (m, { conn, usedPrefix = '.' }) => {
    const body = SECTIONS.map(([icon, title, cmds]) =>
        `┃\n┃ ${icon} *${title}*\n` +
        cmds.map(c => `${usedPrefix}${c.split(':')[0]}${c.includes(':') ? ' (' + c.split(':')[1] + ')' : ''}`)
            .reduce((rows, c) => {
                const last = rows[rows.length - 1]
                if (last && (last + ' • ' + c).length <= 44) rows[rows.length - 1] = last + ' • ' + c
                else rows.push(c)
                return rows
            }, [])
            .map(r => `┃  ${r}`).join('\n')
    ).join('\n')

    const total = Object.values(global.plugins || {}).filter(p => p && p.command && !(Array.isArray(p.command) && !p.command.length)).length
    const text =
`╭━━━━━〔 ⛩️ *𝑺𝑼𝑲𝑼𝑵𝑨* ⛩️ 〕━━━━━⬣
┃  ✦ مميزات البوت ✦
${body}
┃
┣━━━━━━━━━━━━━━━━━━⬣
┃ 📌 ${total ? total + '+ أمر' : 'أوامر كتير'} • ${usedPrefix}اوامر للقايمة الكاملة
╰━━━━━━━━━━━━━━━━━━━━⬣
> ${FOOTER}`

    await conn.sendMessage(m.chat, { text }, { quoted: m })
}

handler.help = ['مميزات']
handler.tags = ['main']
handler.command = /^(مميزات|ميزات|features)$/i

export default handler