const ALL = GROUPS.flatMap(g => g.items)   // الرقم = ترتيب الدعاء من 1

const fmt = n => {
    const [name, text, src] = ALL[n - 1]
    return `╭━━━〔 🤲 *${name}* 〕━━━⬣\n\n${text}\n\n╰━━━━━━━━━━━━━━⬣\n📚 _${src}_\n\n> ${FOOTER}`
}

const menuText = p => {
    let i = 0
    return `🤲 *الأدعية*\n\n` + GROUPS.map(g => `*${g.title}*\n` + g.items.map(it => `${++i}. ${it[0]}`).join('\n')).join('\n\n') + `\n\nاكتب *${p}دعاء <الرقم>*`
}

let handler = async (m, { conn, text, usedPrefix = '.' }) => {
    const reply = t => conn.sendMessage(m.chat, { text: t }, { quoted: m })
    const arg = String(text || '').trim()

    if (arg) {
        const n = parseInt(arg)
        if (n >= 1 && n <= ALL.length) return reply(fmt(n))
        const found = ALL.findIndex(it => it[0].includes(arg))
        if (found >= 0) return reply(fmt(found + 1))
        return reply(`⚠️ مفيش دعاء بالرقم ده. اكتب *${usedPrefix}دعاء* وشوف القايمة.`)
    }

    try {
        if (!lib?.sendList) throw new Error('no sendList')
        let i = 0
        await lib.sendList(conn, m.chat, {
            text: '🤲 *الأدعية الإسلامية*\n\nاضغط على الزر واختار الدعاء 👇',
            footer: FOOTER,
            title: '🤲 الأدعية',
            buttonText: 'اختار الدعاء',
            sections: GROUPS.map(g => ({
                title: g.title,
                rows: g.items.map(it => ({ header: '', title: it[0].slice(0, 24), description: '', id: `${usedPrefix}دعاء ${++i}` })),
            })),
            quoted: m,
        })
    } catch (e) {
        console.error('[دعاء] القايمة فشلت، هبعت نص:', e.message)
        await reply(menuText(usedPrefix))
    }
}

handler.help = ['دعاء']
handler.tags = ['islamic']
handler.command = /^(دعاء|ادعيه|أدعية|ادعية)$/i

export default handler