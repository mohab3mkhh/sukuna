const REACTS = ['😂', '💀', '🤣', '😭', '🔥', '🫏']

if (!global.metinDeck) global.metinDeck = []
if (!global.metinLast) global.metinLast = null

function shuffle(arr) {
    const a = [...arr]
    for (let i = a.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1))
        ;[a[i], a[j]] = [a[j], a[i]]
    }
    return a
}

// كوتشينة: كل الجمل بتتقال مرة قبل ما أي جملة تتكرر
function nextRoast() {
    if (!global.metinDeck.length) {
        const deck = shuffle(ROASTS)
        if (deck[deck.length - 1] === global.metinLast) deck.unshift(deck.pop())
        global.metinDeck = deck
    }
    const roast = global.metinDeck.pop()
    global.metinLast = roast
    return roast
}

let handler = async (m, { conn, args, command }) => {
    // يشتغل بـ  .ميتين توني  أو  .ميتين_توني
    const direct = /^(ميتين_توني|ميتينتوني)$/i.test(command)
    if (!direct && !(args[0] && args[0].includes(T))) return

    try { await conn.sendMessage(m.chat, { react: { text: REACTS[Math.floor(Math.random() * REACTS.length)], key: m.key } }) } catch {}

    await conn.sendMessage(m.chat, { text: `${nextRoast()}\n\n⛩️ SUKUNA BOT ⛩️` }, { quoted: m })
}

